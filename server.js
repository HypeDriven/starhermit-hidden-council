// server=server.js), the one authority for everything recorded:
//
// 1. Hosted councils. A realtime room is the lobby; when the host starts it
//    the platform binds a session to it and this script referees the round
//    (a room-bound session): it deals the roles from its own secret seed,
//    applies every command for the seat the platform says sent it (through
//    the same src/rules.js the solo game runs, written into the RULES block
//    below by tools/build-server.mjs), plays the automata seats, a seat whose
//    player left the room and a seat offline for 30 s with the rules' AI,
//    votes `skip` for a human who has not voted 60 s into a council, and
//    sends each player their own view of the station: their own role (a
//    saboteur also sees the other saboteurs), the dead seats' roles, their
//    own cooldown and votes, never the seed. When the rules end the round (or
//    every human left) it returns the result — the winners, each seat's role
//    and score — which closes the room. No client reports a result.
// 2. Score posting. A finished solo Journey, Daily Chime or Challenge round
//    posts its total on a practice session ({ type: 'result', scores }); the
//    script range-checks it against the high-score board and returns it in
//    `scores`, as score-script.js did (the user's decision: solo scores keep
