var AI_DELAY_MS = 450;        // an automaton acts this long after the last command (the browser build's host)
var AI_STEPS_PER_TICK = 3;    // catch-up cap per tick
var OFFLINE_TAKEOVER_MS = 30000;
var VOTE_DEADLINE_MS = 60000;
var LOG_KEEP = 40;            // station log entries kept in the session document
var LOG_WIRE = 16;            // entries each view carries
