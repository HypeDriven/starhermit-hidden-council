function own(o, k) { return Object.prototype.hasOwnProperty.call(o, k); }
function clampText(s, max) { return String(s == null ? '' : s).replace(/[\u0000-\u001f\u007f]/g, ' ').trim().slice(0, max); }

// --- score posting (practice sessions) -------------------------------------------

function validScore(board, v) {
  if (typeof v !== 'number' || !isFinite(v)) return false;
  if (board.scoreType !== 'decimal' && Math.floor(v) !== v) return false;
  if (board.scoreType === 'time-ms' && v < 0) return false;
  if (board.minScore != null && v < board.minScore) return false;
  if (board.maxScore != null && v > board.maxScore) return false;
  return true;
}

function scoreMessage(ctx) {
  var data = ctx.message.data || {};
  if (data.type !== 'result' || !data.scores || typeof data.scores !== 'object') {
    return { ok: false, error: 'Unknown command' };
  }
  var from = ctx.message.from;
  var scores = {}, accepted = [];
  for (var key in BOARDS) {
    if (!own(BOARDS, key) || !own(data.scores, key)) continue;
    var v = data.scores[key];
    if (!validScore(BOARDS[key], v)) continue;
    scores[key] = {}; scores[key][from] = v; accepted.push(key);
  }
  var state = ctx.sessionState || {};
  state.summary = { status: 'finished' };
  return {
    ok: true,
    sessionState: state,
    scores: scores,
    broadcast: [{ to: [from], data: { type: 'result-ack', accepted: accepted } }],
    result: { kind: 'finished', reason: 'result' }
  };
}

// --- hosted councils ----------------------------------------------------------------

/** Seats from the frozen roster (humans and the room's AI) plus the host's automata. */
function seatsFrom(ctx) {
  var meta = (ctx.room.metadata && typeof ctx.room.metadata === 'object') ? ctx.room.metadata : {};
  var roster = ctx.room.roster || [];
  var seats = [];
  for (var i = 0; i < roster.length && seats.length < MAX_SEATS; i++) {
    var r = roster[i];
    var human = !!(r && !r.ai && typeof r.userId === 'string' && r.userId);
    seats.push({ userId: human ? r.userId : null, name: clampText(r && r.name, NAME_MAX) || (human ? 'Player ' + (i + 1) : AUTOMATON + ' ' + (i + 1)), ai: !human, left: false, offAt: null });
  }
  var extra = typeof meta.automata === 'number' && isFinite(meta.automata) ? Math.max(0, Math.min(MAX_SEATS, Math.floor(meta.automata))) : 0;
  var n = 0;
  while (seats.length < MAX_SEATS && (n < extra || seats.length < MIN_SEATS)) {
    n++;
    seats.push({ userId: null, name: AUTOMATON + ' ' + n, ai: true, left: false, offAt: null });
  }
  return seats;
}

/** The roles dealt again from a secret seed (the public seed only places the tasks). */
function dealRoles(state, roleSeed, saboteurs) {
  var order = [];
  for (var i = 0; i < state.players.length; i++) order.push(i);
  for (var j = order.length - 1; j > 0; j--) {
    var k = Math.floor(Util.rand01(roleSeed, 1000 + j) * (j + 1));
    var t = order[j]; order[j] = order[k]; order[k] = t;
  }
  for (var p = 0; p < state.players.length; p++) state.players[p].role = 'crew';
  for (var s = 0; s < saboteurs; s++) state.players[order[s]].role = 'saboteur';
}

function startCouncil(ctx) {
  var seats = seatsFrom(ctx);
  var seed = (Math.floor(ctx.random * 4294967296) >>> 0) || 1;
  var roleSeed = (Util.hashStr(String(ctx.sessionId || '') + ':' + seed) ^ 0x5bd1e995) >>> 0;
  var saboteurs = seats.length >= 9 ? 2 : 1;
  var state = Rules.createInitialState({
    seed: seed, playerCount: seats.length, saboteurCount: saboteurs, taskCount: 8,
    names: seats.map(function (s) { return s.name; }), sessionId: String(ctx.sessionId || 'hosted')
  });
  dealRoles(state, roleSeed, saboteurs);
  state.log.push({ tick: 0, kind: 'meeting', text: 'The session begins.' });
  var ss = {
    v: 1, mode: 'council', seats: seats, state: state,
    visual: (Util.hashStr('visual:' + seed) % 100000) + 1,
    logTotal: state.log.length, cmd: 0,
    startedAt: ctx.now, lastActAt: ctx.now, meetingAt: null, over: null
  };
  syncAi(ss, ctx);
  return ss;
}

function seatOf(ss, userId) {
  for (var i = 0; i < ss.seats.length; i++) if (ss.seats[i].userId && ss.seats[i].userId === userId) return i;
  return -1;
}

/** Presence: leavers for good, players offline 30 s for now, are played by the AI. */
function syncAi(ss, ctx) {
  var presence = ctx.presence || {};
  for (var i = 0; i < ss.seats.length; i++) {
    var s = ss.seats[i];
    if (!s.ai) {
      var p = presence[s.userId];
      if (p && p.left) s.left = true;
      if (!p || !p.online) { if (s.offAt == null) s.offAt = ctx.now; } else s.offAt = null;
    }
    ss.state.players[i].ai = s.ai || s.left || (s.offAt != null && ctx.now - s.offAt >= OFFLINE_TAKEOVER_MS);
  }
}

function everyHumanLeft(ss) {
  for (var i = 0; i < ss.seats.length; i++) if (!ss.seats[i].ai && !ss.seats[i].left) return false;
  return true;
}

/** Applies a command; keeps the log and the seen ids small. */
function apply(ss, cmd, ctx) {
  var before = ss.state.log.length;
  var phase = ss.state.phase;
  var res = Rules.applyCommand(ss.state, cmd);
  if (!res.state) return res;
  ss.state = res.state;
  ss.logTotal += ss.state.log.length - before;
  if (ss.state.log.length > LOG_KEEP) ss.state.log = ss.state.log.slice(-LOG_KEEP);
  if (ss.state.seen.length > 64) ss.state.seen = ss.state.seen.slice(-64);
  if (ss.state.phase === 'meeting' && phase !== 'meeting') ss.meetingAt = ctx.now;
  if (ss.state.phase !== 'meeting') ss.meetingAt = null;
  return res;
}

function nextId(ss, tag) { ss.cmd += 1; return tag + ss.state.tick + '-' + ss.cmd; }

/** One automaton step, as the browser build's SoloSession.stepAi chose its actor. */
function aiStep(ss, ctx) {
  var st = ss.state;
  if (st.phase === 'over') return false;
  var actor = null, i;
  if (st.phase === 'meeting') {
    for (i = 0; i < st.players.length; i++) {
      var p = st.players[i];
      if (p.ai && p.alive && !own(st.meeting.votes, p.id)) { actor = p; break; }
    }
  } else {
    var alive = st.players.filter(function (q) { return q.ai && q.alive; });
    if (alive.length) actor = alive[st.tick % alive.length];
  }
  if (!actor) return false;
  var cmd = Rules.aiCommand(st, actor.id, nextId(ss, 'ai-'));
  if (!cmd) return false;
  apply(ss, cmd, ctx);
  return true;
}

/** Humans who have not voted 60 s into a council abstain. */
function voteDeadline(ss, ctx) {
  var st = ss.state;
  if (st.phase !== 'meeting' || ss.meetingAt == null || ctx.now - ss.meetingAt < VOTE_DEADLINE_MS) return false;
  var changed = false;
  for (var i = 0; i < st.players.length && ss.state.phase === 'meeting'; i++) {
    var p = ss.state.players[i];
    if (p.alive && !p.ai && !own(ss.state.meeting.votes, p.id)) {
      apply(ss, { id: nextId(ss, 'skip-'), type: 'vote', player: p.id, choice: 'skip' }, ctx);
      changed = true;
    }
  }
  return changed;
}

/** What one seat may see of the station. */
function viewFor(ss, seat) {
  var st = ss.state;
  var me = st.players[seat];
  var over = st.phase === 'over';
  var v = {};
  for (var k in st) if (own(st, k) && k !== 'seed' && k !== 'seen' && k !== 'log') v[k] = st[k];
  v.log = st.log.slice(-LOG_WIRE);
  v.players = st.players.map(function (p) {
    var q = { id: p.id, name: p.name, role: p.role, ai: p.ai, alive: p.alive, room: p.room };
    var knows = over || p.id === me.id || !p.alive || (me.role === 'saboteur' && p.role === 'saboteur');
    if (!knows) q.role = 'crew';
    return q;
  });
  if (!over) {
    v.cooldowns = {};
    if (own(st.cooldowns, me.id)) v.cooldowns[me.id] = st.cooldowns[me.id];
    v.stats = { tasksBy: st.stats.tasksBy, correctVotes: {}, eliminations: {} };
    if (own(st.stats.correctVotes, me.id)) v.stats.correctVotes[me.id] = st.stats.correctVotes[me.id];
    if (own(st.stats.eliminations, me.id)) v.stats.eliminations[me.id] = st.stats.eliminations[me.id];
    if (st.meeting) {
      var votes = {};
      for (var voter in st.meeting.votes) if (own(st.meeting.votes, voter)) votes[voter] = voter === me.id ? st.meeting.votes[voter] : 'hidden';
      v.meeting = { reason: st.meeting.reason, by: st.meeting.by, votes: votes };
    }
  }
  return v;
}

function councilMessage(ss, seat) {
  return {
    type: 'council',
    you: 'p' + seat,
    visual: ss.visual,
    logTotal: ss.logTotal,
    seats: ss.seats.map(function (s, i) { return { name: s.name, ai: s.ai, left: s.left, playerId: 'p' + i }; }),
    state: viewFor(ss, seat),
    over: ss.over
  };
}

function broadcastAll(ss) {
  var out = [];
  for (var i = 0; i < ss.seats.length; i++) {
    var s = ss.seats[i];
    if (!s.ai && !s.left) out.push({ to: [s.userId], data: councilMessage(ss, i) });
  }
  return out;
}

/** The round ended (by the rules, or everyone left): the result, recorded by the platform. */
function finish(ss, ctx, out) {
  var st = ss.state;
  var abandoned = st.phase !== 'over';
  var seats = ss.seats.map(function (s, i) {
    var p = st.players[i];
    var b = Rules.scoreBreakdown(st, p.id);
    return { userId: s.userId, name: s.name, ai: s.ai, left: s.left, role: p.role, alive: p.alive, won: !abandoned && Rules.playerWon(st, p.id), score: b };
  });
  ss.over = {
    winner: abandoned ? null : st.winner, reason: abandoned ? 'abandoned' : st.winReason,
    ticks: st.tick, elapsedTicks: st.elapsedTicks, elapsedMs: Math.max(0, ctx.now - ss.startedAt),
    seats: seats, recorded: true
  };
  out.result = {
    kind: abandoned ? 'abandoned' : 'finished',
    winner: ss.over.winner, reason: ss.over.reason, ticks: st.tick,
    seats: seats.map(function (s) { return { userId: s.userId, name: s.name, ai: s.ai, left: s.left, role: s.role, won: s.won, total: s.score.total }; })
  };
}

function settle(ss, ctx, out, changed) {
  if (!ss.over && (ss.state.phase === 'over' || everyHumanLeft(ss))) { finish(ss, ctx, out); changed = true; }
  out.ok = true;
  out.sessionState = ss;
  if (changed) out.broadcast = (out.broadcast || []).concat(broadcastAll(ss));
  return out;
}

/** The sender's action as a rules command for its own seat; else an error reason. */
function boundCommand(ss, seat, raw) {
  if (!raw || typeof raw !== 'object' || typeof raw.type !== 'string') return { reason: 'bad_command' };
  var type = raw.type;
  if (!own(ACT_FIELDS, type) && type !== 'call' && type !== 'wait') return { reason: 'unknown_type' };
  var cmd = { id: nextId(ss, 'h-'), type: type, player: 'p' + seat };
  if (own(ACT_FIELDS, type)) {
    var f = ACT_FIELDS[type];
    if (typeof raw[f] !== 'string' || raw[f].length > 32) return { reason: 'bad_command' };
    cmd[f] = raw[f];
  }
  return { cmd: cmd };
}

function councilMessageIn(ctx) {
  var ss = ctx.sessionState;
  var from = ctx.message.from;
  var data = ctx.message.data;
  if (!data || typeof data !== 'object') return { ok: false, error: 'bad_command' };
  var seat = seatOf(ss, from);
  var out = {};
  syncAi(ss, ctx);
  switch (data.type) {
    case 'sync':
      if (seat < 0) return { ok: false, error: 'not_seated' };
      out.broadcast = [{ to: [from], data: councilMessage(ss, seat) }];
      return settle(ss, ctx, out, false);
    case 'act': {
      if (ss.over) return { ok: false, error: 'game_over' };
      if (seat < 0 || ss.seats[seat].left) return { ok: false, error: 'not_seated' };
      var bound = boundCommand(ss, seat, data.action);
      if (!bound.cmd) return { ok: false, error: bound.reason };
      var res = apply(ss, bound.cmd, ctx);
      ss.lastActAt = ctx.now;
      if (!res.ok) {
        // A shaped but illegal command still costs its tick (the rules' contract).
        if (res.state) {
          out.broadcast = [{ to: [from], data: { type: 'rejected', reason: res.reason } }];
          return settle(ss, ctx, out, true);
        }
        return { ok: false, error: res.reason };
      }
      return settle(ss, ctx, out, true);
    }
    default:
      return { ok: false, error: 'unknown_command' };
  }
}

function councilTick(ctx) {
  var ss = ctx.sessionState;
  if (ss.over) return { ok: true };
  var wasAi = ss.state.players.map(function (p) { return p.ai; }).join();
  syncAi(ss, ctx);
  var changed = wasAi !== ss.state.players.map(function (p) { return p.ai; }).join();
  if (voteDeadline(ss, ctx)) { changed = true; ss.lastActAt = ctx.now; }
  if (!everyHumanLeft(ss)) {
    for (var n = 0; n < AI_STEPS_PER_TICK && ss.state.phase !== 'over' && ctx.now - ss.lastActAt >= AI_DELAY_MS; n++) {
      if (!aiStep(ss, ctx)) break;
      ss.lastActAt += AI_DELAY_MS;
      changed = true;
    }
    if (ctx.now - ss.lastActAt > AI_DELAY_MS * 4) ss.lastActAt = ctx.now - AI_DELAY_MS;
  }
  if (!changed && ss.state.phase !== 'over' && !everyHumanLeft(ss)) return { ok: true };
  return settle(ss, ctx, {}, changed);
}

globalThis.game = {
  // Four ticks a second: the automata act about every 450 ms, as the browser build's host did.
  tickRateHz: 4,

  createSession: function (ctx) {
    if (ctx.room) return settle(startCouncil(ctx), ctx, {}, true);
    return { ok: true, sessionState: { mode: 'score', startedAt: ctx.now, summary: { status: 'active' } } };
  },

  onPlayerMessage: function (ctx) {
    var ss = ctx.sessionState;
    if (ss && ss.mode === 'council') return councilMessageIn(ctx);
    return scoreMessage(ctx);
  },

  onTick: function (ctx) {
    var ss = ctx.sessionState;
    if (ss && ss.mode === 'council') return councilTick(ctx);
    return { ok: true };
  }
};
